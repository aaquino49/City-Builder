/* Icons.jsx — pixel-style SVG icons for resources. Each icon is a 16x16
   grid drawn with rect "pixels". They scale crisply via shape-rendering. */

function PixelIcon({ pixels, palette, size = 16, style = {} }) {
  // pixels: array of strings, each char is a palette key. ' ' = transparent.
  const rects = [];
  pixels.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (palette[ch]) {
        rects.push(<rect key={`${x},${y}`} x={x} y={y} width="1" height="1" fill={palette[ch]} />);
      }
    }
  });
  return (
    <svg width={size} height={size} viewBox="0 0 16 16" shapeRendering="crispEdges" style={{ display: 'block', ...style }}>
      {rects}
    </svg>
  );
}

